let currentLang: Lang = "id";
const listeners = new Set<(l: Lang) => void>();

export async function initLanguage() {
  const saved = (await storage.getItem<string>("lang", "id")) as Lang;
  if (saved === "en" || saved === "id") currentLang = saved;
}

export function getLang(): Lang {
  return currentLang;
}

export async function setLang(l: Lang) {
  currentLang = l;
  await storage.setItem("lang", l);
  listeners.forEach((cb) => cb(l));
}

export function t(key: string): string {
  return dict[currentLang][key] ?? dict.id[key] ?? key;
}

export function useI18n() {
  const [, force] = useState(0);
  useEffect(() => {
    const cb = () => force((v) => v + 1);
    listeners.add(cb);
    return () => {
      listeners.delete(cb);
    };
  }, []);
  return { t, lang: currentLang, setLang };
}
